//! Kyumei `[[metric]]` claims from the server's metric definitions.
//!
//! One claim per definition, with ID `server.<name>`, verified by source inspection. Its
//! provenance points at the line holding the name literal.
//!
//! * `category` comes from the packages that record the metric (`recorded_in`): a Frontend,
//!   History, Matching or Worker service metric when only that service's packages record it,
//!   otherwise `server-metric`, which covers several services, code they share, and
//!   definitions nothing records.
//! * `instrument` and `unit` come from the constructor. A counter counts; a gauge has no unit
//!   unless the definition declares one; histograms are bytes or counts. A timer's unit
//!   depends on the exporter, so each of its expositions states it.
//! * `purpose` is the definition's description, when it has one.
//! * Expositions are every name and unit the Prometheus endpoint can export the metric
//!   under, with the configuration that produces each. They follow tally's Prometheus
//!   reporter and the OpenTelemetry Prometheus exporter at the versions Temporal pins (the
//!   claim `server.metrics-framework` cites them). The default framework, tally, comes first.
//!
//! Labels are attached where a metric is recorded, so a definition has none. Reviewed label
//! sets live in annotation files, as do purposes for metrics the source does not describe.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use anyhow::{Result, bail};

use crate::claims::{ClaimOptions, toml_str};
use crate::metrics_gen::{Definition, Generated, Kind};

/// Render the claims for every definition in `g`.
pub fn render(g: &Generated, opts: &ClaimOptions) -> Result<String> {
    let mut out = String::new();
    let _ = write!(
        out,
        "# Metrics of Temporal Server {version}: every metric the source defines.\n\
         #\n\
         # Generated by gen-metric-claims from {source}. Do not edit: regenerate it, and put\n\
         # labels, purposes, units and notes in an annotation file instead (docs/knowledge.md).\n\
         #\n\
         #   cargo run -p kyumei-extract --bin gen-metric-claims -- <temporal checkout> -o <this file>\n\
         #\n\
         # `recorded_in` lists the packages whose code refers to the definition; the category\n\
         # follows from them. Expositions are the names and units the Prometheus endpoint can\n\
         # export, by metrics framework and options (claim `server.metrics-framework`).\n",
        version = g.temporal_version,
        source = opts.source_id,
    );
    for d in &g.metrics {
        let exposed = expositions(d)?;
        let _ = write!(
            out,
            "\n[[metric]]\n\
             id = {id}\n\
             name = {name}\n\
             category = {category}\n\
             instrument = {instrument}\n",
            id = toml_str(&format!("server.{}", d.name)),
            name = toml_str(&d.name),
            category = toml_str(category(d)),
            instrument = toml_str(instrument(d.kind)),
        );
        if let Some(unit) = metric_unit(d)? {
            let _ = writeln!(out, "unit = {}", toml_str(unit));
        }
        if let Some(description) = &d.description {
            let _ = writeln!(out, "purpose = {}", toml_str(description));
        }
        let recorded_in: Vec<String> = d.recorded_in().iter().map(|r| toml_str(r)).collect();
        let _ = write!(
            out,
            "go_name = {go_name}\nrecorded_in = [{recorded_in}]\n",
            go_name = toml_str(&d.go_name()),
            recorded_in = recorded_in.join(", "),
        );
        if d.references.is_empty() {
            let _ = writeln!(
                out,
                "notes = [{}]",
                toml_str(&format!(
                    "Nothing in the source refers to `{}` outside its definition, so the server may never record it.",
                    d.go_name()
                ))
            );
        }
        let _ = write!(
            out,
            "scope = {{ server = [{version}] }}\n\
             verification = {{ status = \"verified\", method = \"source-inspection\", on = {on} }}\n\
             provenance = [\n  {{ source = {source}, path = {path}, line = {line}, excerpt = {excerpt} }},\n]\n",
            version = toml_str(&g.temporal_version),
            on = opts.verified_on,
            source = toml_str(&opts.source_id),
            path = toml_str(&d.path),
            line = d.line,
            excerpt = toml_str(&d.excerpt),
        );
        for e in &exposed {
            let _ = write!(
                out,
                "\n[[metric.exposition]]\nname = {}\n",
                toml_str(&e.name)
            );
            if matches!(
                d.kind,
                Kind::Timer | Kind::BytesHistogram | Kind::DimensionlessHistogram
            ) && let Some(unit) = e.unit
            {
                let _ = writeln!(out, "unit = {}", toml_str(unit));
            }
            let _ = writeln!(out, "condition = {}", toml_str(&e.condition));
        }
    }
    Ok(out)
}

/// The claim category: the one service whose packages record the metric, or `server-metric`
/// when several services, shared code, or nothing records it.
pub fn category(d: &Definition) -> &'static str {
    let mut found = None;
    for dir in d.recorded_in() {
        match (service_category(dir), found) {
            (None, _) => return "server-metric",
            (Some(c), Some(f)) if c != f => return "server-metric",
            (Some(c), _) => found = Some(c),
        }
    }
    found.unwrap_or("server-metric")
}

/// The category of a package under one service's directory.
fn service_category(dir: &str) -> Option<&'static str> {
    [
        ("service/frontend", "frontend-metric"),
        ("service/history", "history-metric"),
        ("service/matching", "matching-metric"),
        ("service/worker", "worker-service-metric"),
    ]
    .into_iter()
    .find(|(root, _)| {
        dir.strip_prefix(root)
            .is_some_and(|rest| rest.is_empty() || rest.starts_with('/'))
    })
    .map(|(_, category)| category)
}

fn instrument(kind: Kind) -> &'static str {
    match kind {
        Kind::Counter => "counter",
        Kind::Gauge => "gauge",
        Kind::Timer => "timer",
        Kind::BytesHistogram | Kind::DimensionlessHistogram => "histogram",
    }
}

/// A unit as Temporal writes it, as a Kyumei unit.
fn kyumei_unit(unit: &str) -> Result<&'static str> {
    Ok(match unit {
        "ms" => "milliseconds",
        "s" => "seconds",
        "By" => "bytes",
        "1" => "count",
        other => bail!("unit {other:?} has no Kyumei equivalent"),
    })
}

/// The unit of the recorded values, when it does not depend on the exporter.
fn metric_unit(d: &Definition) -> Result<Option<&'static str>> {
    Ok(match (d.kind, d.unit.as_deref()) {
        (Kind::Timer, _) => None,
        (Kind::Counter, None) => Some("count"),
        (_, Some(unit)) => Some(kyumei_unit(unit)?),
        (_, None) => None,
    })
}

/// A name and unit the Prometheus endpoint exports a metric under, and when.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Exposition {
    pub name: String,
    /// A Kyumei unit, when the values have one.
    pub unit: Option<&'static str>,
    pub condition: String,
}

/// An OpenTelemetry option of the server's metrics configuration (`common/metrics/config.go`),
/// as written in YAML.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Opt {
    WithoutUnitSuffix,
    WithoutCounterSuffix,
    RecordTimerInSeconds,
}

impl Opt {
    fn yaml(self) -> &'static str {
        match self {
            Opt::WithoutUnitSuffix => "withoutUnitSuffix",
            Opt::WithoutCounterSuffix => "withoutCounterSuffix",
            Opt::RecordTimerInSeconds => "recordTimerInSeconds",
        }
    }
}

/// tally, or OpenTelemetry with a set of options.
#[derive(Clone, Debug, PartialEq, Eq)]
enum Framework {
    Tally,
    OpenTelemetry(Vec<Opt>),
}

impl Framework {
    fn has(&self, opt: Opt) -> bool {
        matches!(self, Framework::OpenTelemetry(set) if set.contains(&opt))
    }
}

/// The OpenTelemetry exporter's unit suffixes for the units Temporal uses
/// (`exporters/prometheus/exporter.go`, `unitSuffixes`).
fn unit_suffix(unit: &str) -> Result<&'static str> {
    Ok(match unit {
        "ms" => "_milliseconds",
        "s" => "_seconds",
        "By" => "_bytes",
        "1" => "_ratio",
        other => bail!("unit {other:?} has no known exporter suffix"),
    })
}

/// The unit the OpenTelemetry handler gives the instrument (`otel_metrics_handler.go`):
/// timers are milliseconds unless `recordTimerInSeconds` is set.
fn otel_unit<'a>(d: &'a Definition, f: &Framework) -> Option<&'a str> {
    match d.kind {
        Kind::Timer if f.has(Opt::RecordTimerInSeconds) => Some("s"),
        Kind::Timer => Some("ms"),
        _ => d.unit.as_deref(),
    }
}

/// The options that can change how `d` is exported.
fn relevant(d: &Definition) -> Vec<Opt> {
    let mut opts = Vec::new();
    let otel_has_unit = d.kind == Kind::Timer || d.unit.is_some();
    if otel_has_unit {
        opts.push(Opt::WithoutUnitSuffix);
    }
    if d.kind == Kind::Counter {
        opts.push(Opt::WithoutCounterSuffix);
    }
    if d.kind == Kind::Timer {
        opts.push(Opt::RecordTimerInSeconds);
    }
    opts
}

/// tally, then OpenTelemetry with every subset of `opts`, fewest options first.
fn frameworks(opts: &[Opt]) -> Vec<Framework> {
    let mut subsets: Vec<Vec<Opt>> = (0..1u32 << opts.len())
        .map(|mask| {
            opts.iter()
                .enumerate()
                .filter(|(i, _)| mask & (1 << i) != 0)
                .map(|(_, o)| *o)
                .collect()
        })
        .collect();
    subsets.sort_by_key(Vec::len);
    std::iter::once(Framework::Tally)
        .chain(subsets.into_iter().map(Framework::OpenTelemetry))
        .collect()
}

/// The name and value unit `d` is exported under with framework `f`.
fn exposed(d: &Definition, f: &Framework) -> Result<(String, Option<&'static str>)> {
    match f {
        // tally's Prometheus reporter registers the name unchanged, and observes timers in
        // seconds (tally prometheus/reporter.go, reportTimerHistogram).
        Framework::Tally => {
            let unit = match d.kind {
                Kind::Timer => Some("seconds"),
                _ => metric_unit(d)?,
            };
            Ok((d.name.clone(), unit))
        }
        // The OpenTelemetry exporter's getName: trim `_total` from a counter, add the unit
        // suffix unless the name already ends with it, then add `_total` back.
        Framework::OpenTelemetry(_) => {
            let unit = otel_unit(d, f);
            let counter_suffix = d.kind == Kind::Counter && !f.has(Opt::WithoutCounterSuffix);
            let mut name = d.name.clone();
            if counter_suffix && let Some(trimmed) = name.strip_suffix("_total") {
                name = trimmed.to_owned();
            }
            if let Some(unit) = unit
                && !f.has(Opt::WithoutUnitSuffix)
            {
                let suffix = unit_suffix(unit)?;
                if !name.ends_with(suffix) {
                    name.push_str(suffix);
                }
            }
            if counter_suffix {
                name.push_str("_total");
            }
            let value_unit = match d.kind {
                Kind::Timer => Some(kyumei_unit(unit.unwrap_or("ms"))?),
                _ => metric_unit(d)?,
            };
            Ok((name, value_unit))
        }
    }
}

/// Every distinct name and unit `d` can be exported under, in the order of the first
/// framework that produces it.
pub fn expositions(d: &Definition) -> Result<Vec<Exposition>> {
    let opts = relevant(d);
    let all = frameworks(&opts);
    let mut groups: Vec<(String, Option<&'static str>, Vec<&Framework>)> = Vec::new();
    for f in &all {
        let (name, unit) = exposed(d, f)?;
        match groups.iter_mut().find(|g| g.0 == name && g.1 == unit) {
            Some(g) => g.2.push(f),
            None => groups.push((name, unit, vec![f])),
        }
    }
    Ok(groups
        .into_iter()
        .map(|(name, unit, fs)| Exposition {
            name,
            unit,
            condition: condition(&fs, all.len(), &opts),
        })
        .collect())
}

/// When an exposition applies, in words.
fn condition(fs: &[&Framework], all: usize, opts: &[Opt]) -> String {
    if fs.len() == all {
        return "Either metrics framework, with any options.".to_owned();
    }
    let parts: Vec<String> = fs
        .iter()
        .map(|f| match f {
            Framework::Tally => "The default tally framework".to_owned(),
            Framework::OpenTelemetry(set) if set.is_empty() => {
                if opts.is_empty() {
                    "OpenTelemetry".to_owned()
                } else {
                    "OpenTelemetry with its default options".to_owned()
                }
            }
            Framework::OpenTelemetry(set) => {
                let set: Vec<String> = set
                    .iter()
                    .map(|o| format!("`{}: true`", o.yaml()))
                    .collect();
                format!("OpenTelemetry with {}", set.join(" and "))
            }
        })
        .collect();
    let mut text = match parts.as_slice() {
        [one] => one.clone(),
        [init @ .., last] => format!("{} or {last}", init.join(", ")),
        [] => String::new(),
    };
    text.push('.');
    text
}

/// Exposed names that more than one metric can be exported under, with the metrics.
pub fn shared_names(g: &Generated) -> Result<Vec<(String, Vec<String>)>> {
    let mut by_name: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for d in &g.metrics {
        for e in expositions(d)? {
            let ids = by_name.entry(e.name).or_default();
            if !ids.contains(&d.name) {
                ids.push(d.name.clone());
            }
        }
    }
    Ok(by_name
        .into_iter()
        .filter(|(_, ids)| ids.len() > 1)
        .collect())
}

/// A Markdown report of where each metric is recorded, with the tag helpers called in the
/// recording statement, for reviewing label sets.
pub fn emitters_report(g: &Generated) -> String {
    let mut out = String::new();
    let _ = write!(
        out,
        "# Where Temporal Server {version} records each metric\n\n\
         Generated by `gen-metric-claims --emitters`. Each reference is a line that refers to the\n\
         metric's definition. The tags listed are the tag helpers called in the same statement;\n\
         tags attached earlier, with a handler's `WithTags`, are not seen. Use them as candidates\n\
         when reviewing a label set, not as the label set.\n",
        version = g.temporal_version,
    );
    for d in &g.metrics {
        let _ = write!(
            out,
            "\n## `{name}`\n\n`{go_name}`, {instrument}, {category}, defined at {path}:{line}.\n\n",
            name = d.name,
            go_name = d.go_name(),
            instrument = instrument(d.kind),
            category = category(d),
            path = d.path,
            line = d.line,
        );
        if d.references.is_empty() {
            out.push_str("No references.\n");
        }
        for r in &d.references {
            let _ = write!(out, "- {}:{}", r.path, r.line);
            if !r.tags.is_empty() {
                let _ = write!(out, ": {}", r.tags.join(", "));
            }
            out.push('\n');
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::claims::{diff, verified_on};
    use crate::metrics_gen::{self, tests::checkout};

    fn options() -> ClaimOptions {
        ClaimOptions {
            source_id: "temporal-server-v1.31.0".to_owned(),
            verified_on: "2026-10-03".to_owned(),
        }
    }

    fn generated() -> Generated {
        let dir = checkout();
        metrics_gen::generate(dir.path(), None).expect("generate")
    }

    fn exposed_as(g: &Generated, name: &str) -> Vec<(String, Option<&'static str>, String)> {
        let d = g.metrics.iter().find(|m| m.name == name).expect(name);
        expositions(d)
            .expect("expositions")
            .into_iter()
            .map(|e| (e.name, e.unit, e.condition))
            .collect()
    }

    fn e(
        name: &str,
        unit: Option<&'static str>,
        condition: &str,
    ) -> (String, Option<&'static str>, String) {
        (name.to_owned(), unit, condition.to_owned())
    }

    #[test]
    fn counters_gain_total_under_opentelemetry() {
        let g = generated();
        assert_eq!(
            exposed_as(&g, "service_requests"),
            [
                e(
                    "service_requests",
                    Some("count"),
                    "The default tally framework or OpenTelemetry with `withoutCounterSuffix: true`."
                ),
                e(
                    "service_requests_total",
                    Some("count"),
                    "OpenTelemetry with its default options."
                ),
            ]
        );
    }

    #[test]
    fn gauges_keep_their_name() {
        let g = generated();
        assert_eq!(
            exposed_as(&g, "service_pending_requests"),
            [e(
                "service_pending_requests",
                None,
                "Either metrics framework, with any options."
            )]
        );
    }

    #[test]
    fn timers_are_seconds_under_tally_and_milliseconds_under_opentelemetry() {
        let g = generated();
        assert_eq!(
            exposed_as(&g, "service_latency"),
            [
                e(
                    "service_latency",
                    Some("seconds"),
                    "The default tally framework or OpenTelemetry with `withoutUnitSuffix: true` and `recordTimerInSeconds: true`."
                ),
                e(
                    "service_latency_milliseconds",
                    Some("milliseconds"),
                    "OpenTelemetry with its default options."
                ),
                e(
                    "service_latency",
                    Some("milliseconds"),
                    "OpenTelemetry with `withoutUnitSuffix: true`."
                ),
                e(
                    "service_latency_seconds",
                    Some("seconds"),
                    "OpenTelemetry with `recordTimerInSeconds: true`."
                ),
            ]
        );
    }

    #[test]
    fn histograms_gain_their_unit_suffix() {
        let g = generated();
        assert_eq!(
            exposed_as(&g, "event_blob_size"),
            [
                e(
                    "event_blob_size",
                    Some("bytes"),
                    "The default tally framework or OpenTelemetry with `withoutUnitSuffix: true`."
                ),
                e(
                    "event_blob_size_bytes",
                    Some("bytes"),
                    "OpenTelemetry with its default options."
                ),
            ]
        );
        // The exporter names unit "1" as a ratio.
        assert_eq!(
            exposed_as(&g, "tasks_per_update")[1].0,
            "tasks_per_update_ratio"
        );
    }

    #[test]
    fn categories_follow_the_recording_packages() {
        let g = generated();
        let category_of =
            |name: &str| category(g.metrics.iter().find(|m| m.name == name).expect(name));
        assert_eq!(category_of("event_blob_size"), "matching-metric");
        assert_eq!(category_of("service_requests"), "server-metric");
        assert_eq!(category_of("never_recorded"), "server-metric");
        assert_eq!(
            service_category("service/worker/scanner"),
            Some("worker-service-metric")
        );
        assert_eq!(service_category("service/workers"), None);
    }

    #[test]
    fn claims_render_and_compare() {
        let g = generated();
        let text = render(&g, &options()).expect("render");
        let table: toml::Table = toml::from_str(&text).expect("valid TOML");
        let metrics = table["metric"].as_array().expect("metrics");
        assert_eq!(metrics.len(), 6);
        let requests = metrics
            .iter()
            .find(|m| m["id"].as_str() == Some("server.service_requests"))
            .expect("service_requests");
        assert_eq!(requests["category"].as_str(), Some("server-metric"));
        assert_eq!(requests["unit"].as_str(), Some("count"));
        assert_eq!(
            requests["go_name"].as_str(),
            Some("metrics.ServiceRequests")
        );
        assert_eq!(
            requests["purpose"].as_str(),
            Some("The number of RPC requests received by the service.")
        );
        let provenance = &requests["provenance"].as_array().expect("provenance")[0];
        assert_eq!(provenance["line"].as_integer(), Some(6));
        let unused = metrics
            .iter()
            .find(|m| m["id"].as_str() == Some("server.never_recorded"))
            .expect("never_recorded");
        assert!(
            unused.get("notes").is_some(),
            "an unrecorded metric says so"
        );
        assert_eq!(verified_on(&text).as_deref(), Some("2026-10-03"));
        assert!(diff(&text, &text).expect("diff").is_empty());
        assert!(shared_names(&g).expect("names").is_empty());
        let report = emitters_report(&g);
        assert!(
            report.contains("- common/rpc/interceptor/telemetry.go:11: metrics.OperationTag"),
            "{report}"
        );
    }
}
