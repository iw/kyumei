//! Kyumei `[[dynamic_config]]` claims from the registry.
//!
//! One claim per setting, with ID `dc.<key>`, verified by source inspection. Its provenance
//! points at the line holding the key literal, which is the line Kyumei's verifier re-reads.
//! The registry records the constructor's line, usually the line before it.
//!
//! The claim fields hold:
//!
//! * `setting`: the constructor, e.g. `NewTaskQueueIntSettingWithConstrainedDefault`.
//! * `value_type`: the constructor's value type in lower case. Converter settings over
//!   `StaticGradualChange` read `gradual change (bool)` or `gradual change (int)`.
//! * `default`: durations as Temporal writes them (`5m`), other constants as values, and the
//!   Go source when the default is not a constant, with a note saying so.
//! * `constrained_by`: the dynamic config YAML constraint keys that the setting's precedence
//!   matches on (`common/dynamicconfig/setting_gen.go` and `yaml_loader.go` at v1.31.0).

use std::{
    collections::{BTreeMap, HashMap},
    fmt::Write as _,
    path::Path,
};

use anyhow::{Context as _, Result, bail};
use serde_json::Value;

use crate::registry::{RegistryFile, SettingDef};

/// How the claims are attributed.
#[derive(Clone, Debug)]
pub struct ClaimOptions {
    /// The Kyumei source ID of the checkout, e.g. `temporal-server-v1.31.0`.
    pub source_id: String,
    /// When the claims were verified, `YYYY-MM-DD`.
    pub verified_on: String,
}

/// The YAML constraint keys a scope's precedence matches on, as an operator writes them.
pub fn constrained_by(scope: &str) -> Option<&'static str> {
    Some(match scope {
        "Global" => "global",
        "Namespace" => "namespace",
        "NamespaceID" => "namespaceId",
        "TaskQueue" => "namespace, taskQueueName, taskType",
        "ShardID" => "shardId",
        "TaskType" => "historyTaskType",
        "Destination" => "namespace, destination",
        "ChasmTaskType" => "chasmTaskType",
        _ => return None,
    })
}

/// Render the claims for `reg`. `root` is the checkout `reg` was generated from; it is read
/// again to find each key's line and constructor.
pub fn render(reg: &RegistryFile, root: &Path, opts: &ClaimOptions) -> Result<String> {
    let mut files = SourceFiles::new(root);
    let mut out = String::new();
    let _ = write!(
        out,
        "# Dynamic configuration of Temporal Server {version}: every setting the source registers.\n\
         #\n\
         # Generated by gen-dc-claims from {source}. Do not edit: regenerate it, and put notes\n\
         # and extra provenance in an annotation file instead (docs/knowledge.md).\n\
         #\n\
         #   cargo run -p kyumei-extract --bin gen-dc-claims -- <temporal checkout> -o <this file>\n",
        version = reg.temporal_version,
        source = opts.source_id,
    );
    for s in &reg.settings {
        let at = files.locate(s)?;
        let Some(constrained) = constrained_by(&s.scope) else {
            bail!("{}: unknown scope {}", s.key, s.scope);
        };
        let _ = write!(
            out,
            "\n[[dynamic_config]]\n\
             id = {id}\n\
             key = {key}\n\
             setting = {setting}\n\
             value_type = {value_type}\n\
             default = {default}\n\
             constrained_by = {constrained}\n\
             description = {description}\n",
            id = toml_str(&format!("dc.{}", s.key)),
            key = toml_str(&s.key),
            setting = toml_str(&at.constructor),
            value_type = toml_str(&value_type(s, &at.constructor)),
            default = toml_str(&default_text(s)),
            constrained = toml_str(constrained),
            description = toml_str(&s.description),
        );
        if s.default.is_none() {
            out.push_str(
                "notes = [\"The default is not a constant; it is shown as written in Go.\"]\n",
            );
        }
        let _ = write!(
            out,
            "scope = {{ server = [{version}] }}\n\
             verification = {{ status = \"verified\", method = \"source-inspection\", on = {on} }}\n\
             provenance = [\n  {{ source = {source}, path = {path}, line = {line}, excerpt = {excerpt} }},\n]\n",
            version = toml_str(&reg.temporal_version),
            on = opts.verified_on,
            source = toml_str(&opts.source_id),
            path = toml_str(&at.path),
            line = at.key_line,
            excerpt = toml_str(&at.excerpt),
        );
    }
    Ok(out)
}

/// The verification date of the first claim in a rendered file, so a check made on another
/// day compares what changed in the source, not the date. Any generated claims file works.
pub fn verified_on(text: &str) -> Option<String> {
    let table: toml::Table = toml::from_str(text).ok()?;
    let on = claim_tables(&table).find_map(|c| c.get("verification")?.get("on"))?;
    Some(match on {
        toml::Value::Datetime(d) => d.to_string(),
        other => other.as_str()?.to_owned(),
    })
}

/// What changed between two rendered files of claims, one line per difference: `+` added,
/// `-` removed, `~` changed.
pub fn diff(old: &str, new: &str) -> Result<Vec<String>> {
    let (before, after) = (by_id(old)?, by_id(new)?);
    let mut out = Vec::new();
    for (id, now) in &after {
        let Some(was) = before.get(id) else {
            out.push(format!("+ {id}"));
            continue;
        };
        for (field, v) in now {
            let prev = was.get(field).map(ToString::to_string).unwrap_or_default();
            if prev != v.to_string() {
                out.push(format!("~ {id}: {field} {prev} → {v}"));
            }
        }
        for field in was.keys().filter(|f| !now.contains_key(*f)) {
            out.push(format!("~ {id}: {field} removed"));
        }
    }
    for id in before.keys().filter(|id| !after.contains_key(*id)) {
        out.push(format!("- {id}"));
    }
    Ok(out)
}

fn by_id(text: &str) -> Result<BTreeMap<String, toml::Table>> {
    let table: toml::Table = toml::from_str(text).context("not a claims file")?;
    let mut out = BTreeMap::new();
    for t in claim_tables(&table) {
        if let Some(id) = t.get("id").and_then(toml::Value::as_str) {
            out.insert(id.to_owned(), t.clone());
        }
    }
    Ok(out)
}

/// The claims of a file: the tables of its top-level arrays (`[[dynamic_config]]`,
/// `[[metric]]`).
fn claim_tables(file: &toml::Table) -> impl Iterator<Item = &toml::Table> {
    file.values()
        .filter_map(toml::Value::as_array)
        .flatten()
        .filter_map(toml::Value::as_table)
}

fn value_type(s: &SettingDef, constructor: &str) -> String {
    match s.typ.as_str() {
        "Typed"
            if constructor.ends_with("WithConverter") && s.default_go.contains("GradualChange") =>
        {
            match &s.default {
                Some(Value::Bool(_)) => "gradual change (bool)".to_owned(),
                Some(Value::Number(_)) => "gradual change (int)".to_owned(),
                _ => "gradual change".to_owned(),
            }
        }
        t => t.to_ascii_lowercase(),
    }
}

fn default_text(s: &SettingDef) -> String {
    match &s.default {
        Some(Value::Bool(b)) => b.to_string(),
        Some(Value::Number(_)) if s.typ == "Duration" => match &s.default_display {
            Value::String(d) => d.clone(),
            other => other.to_string(),
        },
        Some(Value::Number(n)) => n.to_string(),
        Some(Value::String(v)) if v.is_empty() => "\"\"".to_owned(),
        Some(Value::String(v)) => v.clone(),
        Some(other) => other.to_string(),
        None => {
            let go = s
                .default_go
                .split_whitespace()
                .collect::<Vec<_>>()
                .join(" ");
            if go.chars().count() > 200 {
                format!("{}…", go.chars().take(199).collect::<String>())
            } else {
                go
            }
        }
    }
}

/// A TOML string literal.
pub(crate) fn toml_str(s: &str) -> String {
    toml::Value::String(s.to_owned()).to_string()
}

/// Where a setting is registered.
struct Located {
    path: String,
    constructor: String,
    key_line: usize,
    excerpt: String,
}

/// Source files of the checkout, read once each.
struct SourceFiles<'a> {
    root: &'a Path,
    lines: HashMap<String, Vec<String>>,
}

impl<'a> SourceFiles<'a> {
    fn new(root: &'a Path) -> Self {
        Self {
            root,
            lines: HashMap::new(),
        }
    }

    /// The constructor on the registry's line, and the first line from there that holds the
    /// key literal.
    fn locate(&mut self, s: &SettingDef) -> Result<Located> {
        let (path, line) = s
            .source
            .rsplit_once(':')
            .with_context(|| format!("{}: source {} has no line", s.key, s.source))?;
        let line: usize = line
            .parse()
            .with_context(|| format!("{}: source line {line}", s.key))?;
        if !self.lines.contains_key(path) {
            let text = std::fs::read_to_string(self.root.join(path))
                .with_context(|| format!("reading {path}"))?;
            self.lines
                .insert(path.to_owned(), text.lines().map(str::to_owned).collect());
        }
        let lines = &self.lines[path];
        let constructor = lines
            .get(line.saturating_sub(1))
            .and_then(|l| {
                l.split(|c: char| !(c.is_ascii_alphanumeric() || c == '_'))
                    .find(|w| w.starts_with("New") && w.contains("Setting"))
            })
            .with_context(|| format!("{}: no setting constructor at {path}:{line}", s.key))?
            .to_owned();
        let quoted = [format!("\"{}\"", s.key), format!("`{}`", s.key)];
        let (index, text) = lines
            .iter()
            .enumerate()
            .skip(line.saturating_sub(1))
            .take(8)
            .find(|(_, l)| quoted.iter().any(|q| l.contains(q.as_str())))
            .with_context(|| format!("{}: key literal not found after {path}:{line}", s.key))?;
        Ok(Located {
            path: path.to_owned(),
            constructor,
            key_line: index + 1,
            excerpt: text.trim().to_owned(),
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::registry_gen;

    const CONSTANTS: &str = r#"package dynamicconfig

var (
	FrontendRPS = NewGlobalIntSetting(
		"frontend.rps",
		2400,
		`FrontendRPS is workflow rate limit per second per-instance`,
	)
	Parts = NewTaskQueueIntSettingWithConstrainedDefault(
		"matching.numTaskqueueReadPartitions",
		defaultNumTaskQueuePartitions,
		`MatchingNumTaskqueueReadPartitions is the number of read partitions for a task queue`,
	)
	Negligible = NewTaskQueueDurationSetting("matching.backlogNegligibleAge", 5*time.Second, "Age \"quoted\".")
	UseNew = NewTaskQueueTypedSettingWithConverter(
		"matching.useNewMatcher",
		ConvertGradualChange(false),
		StaticGradualChange(true),
		`Use the new matcher.`,
	)
	Env = NewShardIDBoolSetting("history.envFlag", os.Getenv("X") == "", "From the environment.")
)
"#;

    fn checkout() -> tempfile::TempDir {
        let dir = tempfile::tempdir().expect("tempdir");
        let write = |rel: &str, text: &str| {
            let path = dir.path().join(rel);
            std::fs::create_dir_all(path.parent().expect("parent")).expect("mkdir");
            std::fs::write(path, text).expect("write");
        };
        write("common/dynamicconfig/constants.go", CONSTANTS);
        write(
            "common/headers/version_checker.go",
            "package headers\n\nconst ServerVersion = \"1.31.0\"\n",
        );
        dir
    }

    fn options() -> ClaimOptions {
        ClaimOptions {
            source_id: "temporal-server-v1.31.0".to_owned(),
            verified_on: "2026-10-03".to_owned(),
        }
    }

    fn rendered(dir: &Path) -> String {
        let generated = registry_gen::generate(dir, None).expect("generate");
        render(&generated.registry, dir, &options()).expect("render")
    }

    fn claim(text: &str, id: &str) -> toml::Table {
        by_id(text).expect("parses")[id].clone()
    }

    #[test]
    fn claims_cite_the_key_line() {
        let dir = checkout();
        let text = rendered(dir.path());
        let parts = claim(&text, "dc.matching.numTaskqueueReadPartitions");
        assert_eq!(
            parts["setting"].as_str(),
            Some("NewTaskQueueIntSettingWithConstrainedDefault")
        );
        assert_eq!(parts["value_type"].as_str(), Some("int"));
        assert_eq!(parts["default"].as_str(), Some("4"));
        assert_eq!(
            parts["constrained_by"].as_str(),
            Some("namespace, taskQueueName, taskType")
        );
        let provenance = &parts["provenance"].as_array().expect("provenance")[0];
        assert_eq!(
            provenance["path"].as_str(),
            Some("common/dynamicconfig/constants.go")
        );
        // The constructor is on line 9; the key literal Kyumei cites is on line 10.
        assert_eq!(provenance["line"].as_integer(), Some(10));
        assert_eq!(
            provenance["excerpt"].as_str(),
            Some("\"matching.numTaskqueueReadPartitions\",")
        );
        assert_eq!(verified_on(&text).as_deref(), Some("2026-10-03"));
    }

    #[test]
    fn values_render_as_operators_read_them() {
        let dir = checkout();
        let text = rendered(dir.path());
        let rps = claim(&text, "dc.frontend.rps");
        assert_eq!(rps["default"].as_str(), Some("2400"));
        assert_eq!(rps["constrained_by"].as_str(), Some("global"));
        let age = claim(&text, "dc.matching.backlogNegligibleAge");
        assert_eq!(age["value_type"].as_str(), Some("duration"));
        assert_eq!(age["default"].as_str(), Some("5s"));
        assert_eq!(age["description"].as_str(), Some("Age \"quoted\"."));
        // A one-line registration: the key line is the constructor line.
        let line = &age["provenance"].as_array().expect("provenance")[0];
        assert!(
            line["excerpt"]
                .as_str()
                .is_some_and(|e| e.starts_with("Negligible = NewTaskQueueDurationSetting("))
        );
        let gradual = claim(&text, "dc.matching.useNewMatcher");
        assert_eq!(
            gradual["value_type"].as_str(),
            Some("gradual change (bool)")
        );
        assert_eq!(gradual["default"].as_str(), Some("true"));
        let env = claim(&text, "dc.history.envFlag");
        assert_eq!(env["constrained_by"].as_str(), Some("shardId"));
        assert_eq!(env["default"].as_str(), Some("os.Getenv(\"X\") == \"\""));
        assert!(env.contains_key("notes"), "a non-constant default says so");
    }

    #[test]
    fn every_scope_has_constraint_keys() {
        for scope in [
            "Global",
            "Namespace",
            "NamespaceID",
            "TaskQueue",
            "ShardID",
            "TaskType",
            "Destination",
            "ChasmTaskType",
        ] {
            assert!(constrained_by(scope).is_some(), "{scope}");
        }
        assert_eq!(constrained_by("Galaxy"), None);
    }

    #[test]
    fn diff_names_what_changed() {
        let dir = checkout();
        let before = rendered(dir.path());
        let changed = CONSTANTS
            .replace("2400,", "3000,")
            .replace("\tEnv = NewShardIDBoolSetting(\"history.envFlag\", os.Getenv(\"X\") == \"\", \"From the environment.\")\n", "");
        std::fs::write(
            dir.path().join("common/dynamicconfig/constants.go"),
            changed,
        )
        .expect("write");
        let after = rendered(dir.path());
        let d = diff(&before, &after).expect("diff");
        assert!(
            d.iter()
                .any(|l| l == "~ dc.frontend.rps: default \"2400\" → \"3000\""),
            "{d:?}"
        );
        assert!(d.iter().any(|l| l == "- dc.history.envFlag"), "{d:?}");
        assert!(diff(&before, &before).expect("diff").is_empty());
    }
}
