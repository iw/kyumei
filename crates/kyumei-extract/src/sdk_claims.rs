//! Kyumei `[[metric]]` claims for SDK metrics, one per name across the Core, Go and Java SDKs.
//!
//! A claim, with ID `sdk.<name>`, holds the instrument the SDKs agree on, Core's description
//! as its purpose when Core defines the metric, and per family a scope entry, a provenance
//! line (the name's string literal) and the expositions that family's exporters produce. The
//! exposition rules follow each exporter's code at the version the claims cite (the
//! statements `sdk.core-prometheus-naming`, `sdk.go-metrics-naming` and
//! `sdk.java-metrics-naming`):
//!
//! * **Core**'s Prometheus exporter prefixes `temporal_`. `counters_total_suffix` appends
//!   `_total` to counters; durations are milliseconds unless `use_seconds_for_durations` is
//!   set, and `unit_suffix` appends the unit to histograms.
//! * **Go** names include the prefix. The tally handler exports them unchanged unless the scope
//!   is wrapped in `NewPrometheusNamingScope`, which appends `_total` to counters and `_seconds`
//!   to timers. The OpenTelemetry handler records timers in seconds, which its Prometheus
//!   exporter suffixes `_seconds`, and counters as up-down counters, which the exporter writes
//!   as gauges, unless `UseMonotonicCounters` is set.
//! * **Java** names include the prefix. Through `MicrometerClientStatsReporter` and Micrometer's
//!   Prometheus registry, counters gain `_total`, timers become `_seconds` histograms, and tally
//!   histograms are not reported.
//!
//! Labels are attached where a metric is recorded; reviewed label sets live in annotations.

use std::fmt::Write as _;

use anyhow::{Result, bail};

use crate::claims::toml_str;
use crate::sdk_gen::{Family, Generated, Kind, KindBasis, SdkMetric};

/// How one family's claims are attributed.
#[derive(Clone, Debug)]
pub struct FamilySource {
    /// The Kyumei source ID, e.g. `sdk-go-v1.44.0`.
    pub source_id: String,
    /// The revision recorded in claim scopes, e.g. `sdk-go v1.44.0`.
    pub revision: String,
}

/// How the claims are attributed.
#[derive(Clone, Debug)]
pub struct SdkClaimOptions {
    pub verified_on: String,
    pub core: FamilySource,
    pub go: FamilySource,
    pub java: FamilySource,
}

impl SdkClaimOptions {
    fn source(&self, family: Family) -> &FamilySource {
        match family {
            Family::Core => &self.core,
            Family::Go => &self.go,
            Family::Java => &self.java,
        }
    }
}

/// Render one claim per metric name.
pub fn render(g: &Generated, opts: &SdkClaimOptions) -> Result<String> {
    let mut out = String::new();
    let scanned: Vec<String> = g
        .scans
        .iter()
        .map(|(f, _)| opts.source(*f).source_id.clone())
        .collect();
    let _ = write!(
        out,
        "# SDK metrics: every metric the Core, Go and Java SDKs define and record.\n\
         #\n\
         # Generated by gen-sdk-metric-claims from {sources}. Do not edit: regenerate it, and put\n\
         # labels, units and notes in an annotation file instead (docs/knowledge.md).\n\
         #\n\
         #   cargo run -p kyumei-extract --bin gen-sdk-metric-claims -- \\\n\
         #     --core <sdk-rust checkout> --go <sdk-go module> --java <sdk-java checkout> -o <this file>\n\
         #\n\
         # Names are unprefixed; each SDK family's expositions give the names its exporters\n\
         # produce (claims `sdk.core-prometheus-naming`, `sdk.go-metrics-naming` and\n\
         # `sdk.java-metrics-naming`).\n",
        sources = scanned.join(", "),
    );
    for (name, metrics) in g.by_name() {
        render_claim(&mut out, name, &metrics, opts)?;
    }
    Ok(out)
}

fn render_claim(
    out: &mut String,
    name: &str,
    metrics: &[&SdkMetric],
    opts: &SdkClaimOptions,
) -> Result<()> {
    let first = metrics[0];
    let inst = instrument(first.kind);
    if let Some(other) = metrics.iter().find(|m| instrument(m.kind) != inst) {
        bail!(
            "{name} is a {} in {} ({}:{}) but a {} in {} ({}:{})",
            first.kind.label(),
            first.family.token(),
            first.path,
            first.line,
            other.kind.label(),
            other.family.token(),
            other.path,
            other.line
        );
    }
    let _ = write!(
        out,
        "\n[[metric]]\n\
         id = {id}\n\
         name = {name_lit}\n\
         category = \"sdk-metric\"\n\
         instrument = {instrument}\n",
        id = toml_str(&format!("sdk.{name}")),
        name_lit = toml_str(name),
        instrument = toml_str(inst),
    );
    if first.kind == Kind::Counter {
        out.push_str("unit = \"count\"\n");
    }
    if let Some(description) = metrics.iter().find_map(|m| m.description.as_deref()) {
        let _ = writeln!(out, "purpose = {}", toml_str(description));
    }
    let mut notes = Vec::new();
    for m in metrics {
        if let KindBasis::ConstantName(constant) = &m.kind_basis {
            notes.push(format!(
                "The {} SDK passes `{constant}` to its recording call through other code, so the kind is read from the constant's name.",
                family_name(m.family)
            ));
        }
        if m.family == Family::Java && m.kind == Kind::Histogram {
            notes.push(
                "The Java SDK records this as a tally histogram, which `MicrometerClientStatsReporter` does not report."
                    .to_owned(),
            );
        }
    }
    if !notes.is_empty() {
        let notes: Vec<String> = notes.iter().map(|n| toml_str(n)).collect();
        let _ = writeln!(out, "notes = [{}]", notes.join(", "));
    }
    let scope: Vec<String> = metrics
        .iter()
        .map(|m| {
            format!(
                "{{ family = {}, revision = {} }}",
                toml_str(m.family.token()),
                toml_str(&opts.source(m.family).revision)
            )
        })
        .collect();
    let _ = write!(
        out,
        "scope = {{ sdk = [{scope}] }}\n\
         verification = {{ status = \"verified\", method = \"source-inspection\", on = {on} }}\n\
         provenance = [\n",
        scope = scope.join(", "),
        on = opts.verified_on,
    );
    for m in metrics {
        let _ = writeln!(
            out,
            "  {{ source = {}, path = {}, line = {}, excerpt = {} }},",
            toml_str(&opts.source(m.family).source_id),
            toml_str(&m.path),
            m.line,
            toml_str(&m.excerpt)
        );
    }
    out.push_str("]\n");
    for m in metrics {
        for e in expositions(m)? {
            let _ = write!(
                out,
                "\n[[metric.exposition]]\nname = {}\nsdk_family = {}\n",
                toml_str(&e.name),
                toml_str(m.family.token())
            );
            if matches!(m.kind, Kind::Duration | Kind::Histogram)
                && let Some(unit) = e.unit
            {
                let _ = writeln!(out, "unit = {}", toml_str(unit));
            }
            let _ = writeln!(out, "condition = {}", toml_str(&e.condition));
        }
    }
    Ok(())
}

fn instrument(kind: Kind) -> &'static str {
    match kind {
        Kind::Counter => "counter",
        Kind::Gauge => "gauge",
        Kind::Duration | Kind::Histogram => "histogram",
    }
}

fn family_name(family: Family) -> &'static str {
    match family {
        Family::Core => "Core",
        Family::Go => "Go",
        Family::Java => "Java",
    }
}

/// A name and unit one SDK family exports a metric under, and when.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Exposition {
    pub name: String,
    pub unit: Option<&'static str>,
    pub condition: String,
}

/// One exporter configuration: the name and unit it produces, and how it is described.
struct Config {
    name: String,
    unit: Option<&'static str>,
    describes: &'static str,
}

/// Every distinct name and unit `m` is exported under by its family.
pub fn expositions(m: &SdkMetric) -> Result<Vec<Exposition>> {
    let base = format!("temporal_{}", m.name);
    let count = Some("count");
    let configs: Vec<Config> = match (m.family, m.kind) {
        // crates/common/src/telemetry/prometheus_meter.rs: `metric_name.push_str("_total")` when
        // `counters_total_suffix` is set; `format!("{base_name}_{unit}")` when `unit_suffix` is.
        (Family::Core, Kind::Counter) => vec![
            Config {
                name: base.clone(),
                unit: count,
                describes: "by default",
            },
            Config {
                name: format!("{base}_total"),
                unit: count,
                describes: "with `counters_total_suffix`",
            },
        ],
        (Family::Core, Kind::Gauge) => {
            vec![Config {
                name: base.clone(),
                unit: None,
                describes: "with any options",
            }]
        }
        (Family::Core, Kind::Duration) => vec![
            Config {
                name: base.clone(),
                unit: Some("milliseconds"),
                describes: "by default",
            },
            Config {
                name: base.clone(),
                unit: Some("seconds"),
                describes: "with `use_seconds_for_durations`",
            },
            Config {
                name: format!("{base}_milliseconds"),
                unit: Some("milliseconds"),
                describes: "with `unit_suffix`",
            },
            Config {
                name: format!("{base}_seconds"),
                unit: Some("seconds"),
                describes: "with `unit_suffix` and `use_seconds_for_durations`",
            },
        ],
        (Family::Go, Kind::Counter) => {
            let total = with_suffix(&base, "_total");
            // The OpenTelemetry exporter trims `_total` before adding it back.
            let otel_total = format!("{}_total", base.strip_suffix("_total").unwrap_or(&base));
            vec![
                Config {
                    name: base.clone(),
                    unit: count,
                    describes: "the tally handler",
                },
                Config {
                    name: total,
                    unit: count,
                    describes: "the tally handler with `NewPrometheusNamingScope`",
                },
                Config {
                    name: base.clone(),
                    unit: count,
                    describes: "the OpenTelemetry handler by default",
                },
                Config {
                    name: otel_total,
                    unit: count,
                    describes: "the OpenTelemetry handler with `UseMonotonicCounters`",
                },
            ]
        }
        (Family::Go, Kind::Gauge) => {
            vec![Config {
                name: base.clone(),
                unit: None,
                describes: "any metrics handler",
            }]
        }
        (Family::Go, Kind::Duration) => vec![
            Config {
                name: base.clone(),
                unit: Some("seconds"),
                describes: "the tally handler",
            },
            Config {
                name: with_suffix(&base, "_seconds"),
                unit: Some("seconds"),
                describes: "the tally handler with `NewPrometheusNamingScope`",
            },
            Config {
                name: with_suffix(&base, "_seconds"),
                unit: Some("seconds"),
                describes: "the OpenTelemetry handler",
            },
            Config {
                name: base.clone(),
                unit: Some("seconds"),
                describes: "the OpenTelemetry handler with the exporter's `WithoutUnits`",
            },
        ],
        // Micrometer appends `_total` to counters (1.9.9's naming convention; with 1.13.6 the
        // Prometheus client strips and re-adds it), and `_seconds` to timers.
        (Family::Java, Kind::Counter) => vec![Config {
            name: with_suffix(&base, "_total"),
            unit: count,
            describes: "",
        }],
        (Family::Java, Kind::Gauge) => vec![Config {
            name: base.clone(),
            unit: None,
            describes: "",
        }],
        (Family::Java, Kind::Duration) => vec![Config {
            name: with_suffix(&base, "_seconds"),
            unit: Some("seconds"),
            describes: "",
        }],
        (Family::Java, Kind::Histogram) => Vec::new(),
        (family, Kind::Histogram) => bail!(
            "{} records {} as a value histogram, whose exposition rules are not verified",
            family_name(family),
            m.name
        ),
    };
    let mut groups: Vec<(String, Option<&'static str>, Vec<&'static str>)> = Vec::new();
    for c in configs {
        match groups.iter_mut().find(|g| g.0 == c.name && g.1 == c.unit) {
            Some(g) => g.2.push(c.describes),
            None => groups.push((c.name, c.unit, vec![c.describes])),
        }
    }
    Ok(groups
        .into_iter()
        .map(|(name, unit, describes)| Exposition {
            condition: condition(m.family, &describes),
            name,
            unit,
        })
        .collect())
}

fn with_suffix(name: &str, suffix: &str) -> String {
    if name.ends_with(suffix) {
        name.to_owned()
    } else {
        format!("{name}{suffix}")
    }
}

fn condition(family: Family, describes: &[&str]) -> String {
    let joined = describes.join(", or ");
    match family {
        Family::Core => format!("Core's Prometheus exporter {joined}."),
        Family::Go => format!("Go SDK with {joined}."),
        Family::Java => {
            "Java SDK with `MicrometerClientStatsReporter` and Micrometer's Prometheus registry."
                .to_owned()
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn metric(family: Family, name: &str, kind: Kind) -> SdkMetric {
        SdkMetric {
            family,
            name: name.to_owned(),
            kind,
            kind_basis: KindBasis::Recording,
            description: None,
            path: "x".to_owned(),
            line: 1,
            excerpt: String::new(),
        }
    }

    fn names(family: Family, name: &str, kind: Kind) -> Vec<(String, Option<&'static str>)> {
        expositions(&metric(family, name, kind))
            .expect("expositions")
            .into_iter()
            .map(|e| (e.name, e.unit))
            .collect()
    }

    fn n(name: &str, unit: Option<&'static str>) -> (String, Option<&'static str>) {
        (name.to_owned(), unit)
    }

    #[test]
    fn each_family_names_counters_its_own_way() {
        assert_eq!(
            names(
                Family::Core,
                "workflow_task_queue_poll_succeed",
                Kind::Counter
            ),
            [
                n("temporal_workflow_task_queue_poll_succeed", Some("count")),
                n(
                    "temporal_workflow_task_queue_poll_succeed_total",
                    Some("count")
                ),
            ]
        );
        assert_eq!(
            names(
                Family::Java,
                "workflow_task_queue_poll_succeed",
                Kind::Counter
            ),
            [n(
                "temporal_workflow_task_queue_poll_succeed_total",
                Some("count")
            )]
        );
        // A name that already ends in `_total`: Core appends another, Go and Java do not.
        assert_eq!(
            names(Family::Core, "local_activity_total", Kind::Counter)[1].0,
            "temporal_local_activity_total_total"
        );
        assert_eq!(
            names(Family::Go, "local_activity_total", Kind::Counter),
            [n("temporal_local_activity_total", Some("count"))]
        );
        let go = expositions(&metric(Family::Go, "request", Kind::Counter)).expect("go");
        assert_eq!(
            go[0].condition,
            "Go SDK with the tally handler, or the OpenTelemetry handler by default."
        );
    }

    #[test]
    fn durations_carry_their_units() {
        assert_eq!(
            names(
                Family::Core,
                "workflow_task_schedule_to_start_latency",
                Kind::Duration
            ),
            [
                n(
                    "temporal_workflow_task_schedule_to_start_latency",
                    Some("milliseconds")
                ),
                n(
                    "temporal_workflow_task_schedule_to_start_latency",
                    Some("seconds")
                ),
                n(
                    "temporal_workflow_task_schedule_to_start_latency_milliseconds",
                    Some("milliseconds")
                ),
                n(
                    "temporal_workflow_task_schedule_to_start_latency_seconds",
                    Some("seconds")
                ),
            ]
        );
        assert_eq!(
            names(
                Family::Go,
                "workflow_task_schedule_to_start_latency",
                Kind::Duration
            ),
            [
                n(
                    "temporal_workflow_task_schedule_to_start_latency",
                    Some("seconds")
                ),
                n(
                    "temporal_workflow_task_schedule_to_start_latency_seconds",
                    Some("seconds")
                ),
            ]
        );
        assert_eq!(
            names(
                Family::Java,
                "workflow_task_schedule_to_start_latency",
                Kind::Duration
            ),
            [n(
                "temporal_workflow_task_schedule_to_start_latency_seconds",
                Some("seconds")
            )]
        );
        assert!(names(Family::Java, "replay", Kind::Histogram).is_empty());
    }
}
